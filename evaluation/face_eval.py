"""
Step 1 entry point: measure the face modality and write the report.

    venv/Scripts/python.exe -m evaluation.face_eval

Requires the extraction cache; run `python -m evaluation.extract` first.

Produces, in evaluation/output/:
    face_eval_report.md      the written report (numbers + caveats)
    tolerance_sweep.csv      Protocol B across tolerance values
    blend_sweep.csv          Protocol B across confidence-blend weights
    *.png                    figures

This module only reads the cache and writes reports. It imports nothing from
the live authentication path except config (for the current threshold values it
is testing), and it changes nothing.
"""

import argparse
import csv
import os
import sys
from typing import Dict, List, Optional, Tuple

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import config
from evaluation import extract, metrics, pairs, plots, protocols

OUTPUT_DIR = plots.OUTPUT_DIR

# The blend has an algebraic floor; see protocols.report_high_risk_floor.
HIGH_RISK_FLOOR = getattr(config, "RISK_HIGH_FACE_MIN_CONFIDENCE", 0.75)


# ── Cache loading + alignment ────────────────────────────────


def _key(row: Dict[str, str]) -> Tuple[str, str]:
    return row["user_id"], row["filename"]


def load_aligned(det_a: int, det_b: int):
    """Load two extractions restricted to the images present in both.

    Detection can succeed at one input size and fail at another, so the two
    caches are not guaranteed to cover the same images. Comparing them
    positionally without checking would silently pair up different photographs.
    """
    rows_a, emb_a = extract.load(det_a)
    rows_b, emb_b = extract.load(det_b)

    index_b = {_key(r): i for i, r in enumerate(rows_b)}
    keep_a, keep_b = [], []
    for i, row in enumerate(rows_a):
        j = index_b.get(_key(row))
        if j is not None:
            keep_a.append(i)
            keep_b.append(j)

    dropped = len(rows_a) - len(keep_a)
    aligned_rows = [rows_a[i] for i in keep_a]
    return (aligned_rows, emb_a[keep_a], emb_b[keep_b], dropped)


# ── Report helpers ───────────────────────────────────────────


class Report:
    """Accumulates report lines while echoing them to stdout."""

    def __init__(self):
        self.lines: List[str] = []

    def __call__(self, text: str = ""):
        self.lines.append(text)
        try:
            print(text)
        except UnicodeEncodeError:
            # Windows consoles default to cp1252 and cannot render the report's
            # symbols. The file is written as UTF-8 regardless, so degrade only
            # the terminal echo rather than losing the run.
            encoding = getattr(sys.stdout, "encoding", None) or "ascii"
            print(text.encode(encoding, "replace").decode(encoding, "replace"))

    def heading(self, text: str):
        self("")
        self(f"## {text}")
        self("")

    def write(self, path: str):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write("\n".join(self.lines) + "\n")


def _pct(value: float, n_trials: Optional[int] = None) -> str:
    """Format a rate, attaching a confidence bound when zero events occurred.

    A measured zero is a sample-size statement, not a property of the system.
    Where the trial count is known, the rule-of-three 95% upper bound is shown
    instead of a bare 0%, so no number in this report can be quoted as
    "perfect" without its caveat travelling with it.
    """
    if value != value:          # NaN
        return "n/a"
    if value == 0:
        if n_trials:
            return f"0 obs. (<{metrics.rule_of_three(n_trials):.4%})"
        return "0 observed"
    return f"{value:.4%}"


def write_csv(path: str, rows: List[Dict]):
    if not rows:
        return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


# ── The evaluation ───────────────────────────────────────────


def run(gallery_det: int = 640, probe_det: int = 320,
        make_plots: bool = True) -> Report:
    report = Report()
    tolerance = config.FACE_RECOGNITION_TOLERANCE
    min_confidence = config.MIN_FACE_CONFIDENCE

    rows, gallery_emb, probe_emb, dropped = load_aligned(gallery_det, probe_det)
    labels = pairs.label_array(rows)
    scale = pairs.counts(labels)

    report("# Face modality evaluation")
    report("")
    report("Generated by `python -m evaluation.face_eval`. Reads the enrolled "
           "dataset only; changes nothing.")

    # ── Scale ──
    report.heading("1. Dataset")
    report(f"- Samples: **{scale['n_samples']}** images across "
           f"**{scale['n_users']} users**")
    report(f"- Genuine pairs: **{scale['n_genuine_pairs']:,}**")
    report(f"- Impostor pairs: **{scale['n_impostor_pairs']:,}**")
    report(f"- Gallery extracted at det_size **{gallery_det}** "
           f"(matches `face_encoder.py` enrollment)")
    report(f"- Probes extracted at det_size **{probe_det}** "
           f"(matches `config.FACE_DET_SIZE` at runtime)")
    if dropped:
        report(f"- ⚠️ {dropped} image(s) detected at one size but not the "
               f"other; excluded so both sides cover identical images.")
    report("")
    report("> ⚠️ **Caveat that limits every number below.** All images for a "
           "user come from a single capture session — same lighting, same day, "
           "same appearance. Genuine pairs are therefore optimistically "
           "similar, so the measured FRR is a **lower bound** and the true "
           "operational figure will be worse. Cross-session capture is the fix.")

    # ── Protocol A ──
    report.heading("2. Protocol A — pairwise verification (measures ArcFace)")
    a = protocols.protocol_a(gallery_emb, labels, tolerance)
    s = a["summary"]
    report(f"| Metric | Value |")
    report(f"|:--|:--|")
    report(f"| Genuine distance | {s['genuine_mean']:.4f} ± {s['genuine_std']:.4f} |")
    report(f"| Impostor distance | {s['impostor_mean']:.4f} ± {s['impostor_std']:.4f} |")
    report(f"| Separation (d′) | **{s['d_prime']:.3f}** |")
    report(f"| AUC | **{s['auc']:.6f}** |")
    report(f"| EER | **{s['eer_eer']:.4%}** at distance {s['eer_threshold']:.4f} |")
    report(f"| FAR @ current {tolerance:.2f} | "
           f"{_pct(s['operating_far'], scale['n_impostor_pairs'])} |")
    report(f"| FRR @ current {tolerance:.2f} | "
           f"{_pct(s['operating_frr'], scale['n_genuine_pairs'])} |")
    report("")
    report(f"The EER threshold ({s['eer_threshold']:.4f}) is where FAR and FRR "
           f"balance. The deployed tolerance is {tolerance:.2f}; the gap "
           f"between them is the margin the project trades toward "
           f"{'fewer false accepts' if tolerance < s['eer_threshold'] else 'fewer false rejects'}.")
    report("")
    report("> **Reading a zero.** Observing no errors in *n* trials does not "
           "mean the rate is zero — it means it lies below roughly 3/*n* with "
           "95% confidence (the rule of three). Every zero in this report "
           "carries that bound, so none of them should be quoted as "
           "\"perfect\".")

    # ── Protocol B ──
    report.heading("3. Protocol B — the deployed rule (measures this system)")
    report("Leave-one-image-out, reproducing `face_recognizer."
           "recognize_from_frame()`: tolerance gate, vote, 0.6/0.4 blend, and "
           "the `MIN_FACE_CONFIDENCE` floor.")
    report("")

    b_matched = protocols.protocol_b(gallery_emb, labels,
                                     tolerance=tolerance,
                                     min_confidence=min_confidence)
    b_deployed = protocols.protocol_b(gallery_emb, labels, probe_emb,
                                      tolerance=tolerance,
                                      min_confidence=min_confidence)

    report(f"| Outcome | Gallery {gallery_det} / probe {gallery_det} | "
           f"Gallery {gallery_det} / probe {probe_det} (**deployed**) |")
    report(f"|:--|--:|--:|")
    for label, key in (("Correctly identified", "genuine_correct"),
                       ("Falsely rejected", "genuine_rejected"),
                       ("Mis-identified as another user", "genuine_misidentified"),
                       ("Impostors correctly rejected", "impostor_rejected"),
                       ("Impostors falsely accepted", "impostor_accepted")):
        report(f"| {label} | {b_matched[key]} / {b_matched['n_trials']} | "
               f"{b_deployed[key]} / {b_deployed['n_trials']} |")
    n = b_deployed["n_trials"]
    report(f"| **FRR** | {_pct(b_matched['frr'], n)} | "
           f"{_pct(b_deployed['frr'], n)} |")
    report(f"| **FAR** | {_pct(b_matched['far'], n)} | "
           f"{_pct(b_deployed['far'], n)} |")
    report(f"| **Mis-identification rate** | "
           f"{_pct(b_matched['misidentification_rate'], n)} | "
           f"{_pct(b_deployed['misidentification_rate'], n)} |")
    report("")

    # The pairwise-vs-system gap is the substantive result here, and it is easy
    # to miss when both columns read as zeros.
    pairwise_frr = s["operating_frr"]
    if pairwise_frr > 0 and b_deployed["frr"] == 0:
        n_bad_pairs = int(round(pairwise_frr * scale["n_genuine_pairs"]))
        report(f"> **Why the system beats its own embedding.** Protocol A "
               f"rejects {pairwise_frr:.4%} of genuine *pairs* "
               f"({n_bad_pairs} of {scale['n_genuine_pairs']:,}) at this "
               f"tolerance, yet Protocol B rejects no genuine *user*. The "
               f"difference is the gallery: recognition takes the minimum "
               f"distance over ~19 enrolled images, so one unflattering "
               f"capture cannot reject a user as long as another matches. "
               f"That is a measurable argument for multi-image enrollment, "
               f"and it is invisible to pairwise evaluation.")
        report("")

    report("Mis-identification is separated from rejection deliberately. Being "
           "turned away is an availability failure; being recognised as a "
           "*different enrolled user* is a security failure. At the ATM the "
           "card-owner check catches it, but `/api/auth/face-login` has no "
           "such cross-check.")

    if b_deployed["misidentified_trials"]:
        report("")
        report("Mis-identified trials (deployed configuration):")
        report("")
        report("| Sample | True user | Matched as |")
        report("|:--|:--|:--|")
        for idx, true_id, predicted in b_deployed["misidentified_trials"][:20]:
            report(f"| {rows[idx]['filename']} | {true_id} | {predicted} |")

    # ── High-risk floor ──
    report.heading("4. Is the high-risk confidence floor doing anything?")
    floor_report = protocols.report_high_risk_floor(b_deployed, HIGH_RISK_FLOOR)
    report(f"`RISK_HIGH_FACE_MIN_CONFIDENCE = {HIGH_RISK_FLOOR}` is tested at "
           f"`webapp/backend/auth.py:358` against the **blended** confidence.")
    report("")
    report(f"- Genuine acceptances measured: **{floor_report['n_accepted']}**")
    report(f"- Lowest confidence among them: "
           f"**{floor_report['min_confidence']:.4f}**")
    report(f"- Falling below the {HIGH_RISK_FLOOR} floor: "
           f"**{floor_report['n_below_floor']}** — a rate of "
           f"{_pct(floor_report['fraction_below_floor'], floor_report['n_accepted'])}")
    report("")
    if floor_report.get("inert"):
        report("> **Finding: the control is inert.** No genuine acceptance "
               "fell below the floor, so the 'stricter check for high-risk "
               "sessions' rejects nothing it would not already reject. "
               "Clearing the tolerance gate forces confidence ≥ 0.60, and a "
               "probe matching only its own user gives vote_confidence = 1.0, "
               "so the blend cannot drop below 0.6·0.60 + 0.4·1.0 = 0.76 — "
               "above the 0.75 floor by construction. Applying the floor to "
               "the raw cosine confidence instead of the blended value would "
               "make it bite.")
    else:
        report(f"> The floor does reject some genuine acceptances "
               f"({_pct(floor_report['fraction_below_floor'])}), so it is "
               f"active rather than inert — at a measurable availability cost.")

    # ── Sweeps ──
    report.heading("5. Threshold sweeps")
    tolerances = np.round(np.arange(0.20, 0.81, 0.01), 4)
    tol_rows = protocols.sweep_tolerance(gallery_emb, labels, tolerances,
                                         probe_emb,
                                         min_confidence=min_confidence)
    write_csv(os.path.join(OUTPUT_DIR, "tolerance_sweep.csv"), tol_rows)

    zero_far = [r for r in tol_rows if r["far"] == 0.0]
    best_zero_far = max(zero_far, key=lambda r: r["tolerance"]) if zero_far else None

    report(f"Swept `FACE_RECOGNITION_TOLERANCE` over "
           f"[{tolerances[0]:.2f}, {tolerances[-1]:.2f}] "
           f"→ `tolerance_sweep.csv`.")
    report("")
    if best_zero_far:
        report(f"- Loosest tolerance still admitting **zero** impostors: "
               f"**{best_zero_far['tolerance']:.2f}** "
               f"(FRR {_pct(best_zero_far['frr'], n)})")
        report(f"- Current setting is **{tolerance:.2f}**, i.e. "
               f"{best_zero_far['tolerance'] - tolerance:.2f} stricter than it "
               f"needs to be on this data. That headroom is not waste: it is "
               f"the margin absorbing the harder conditions this dataset does "
               f"not contain (§1). But it is now a *measured* margin rather "
               f"than an inherited constant.")
    report(f"- Current setting **{tolerance:.2f}** → "
           f"FRR {_pct(b_deployed['frr'], n)}, FAR {_pct(b_deployed['far'], n)}")

    blend_weights = np.round(np.arange(0.0, 1.01, 0.05), 4)
    blend_rows = protocols.sweep_blend(gallery_emb, labels, blend_weights,
                                       probe_emb, tolerance=tolerance,
                                       min_confidence=min_confidence)
    write_csv(os.path.join(OUTPUT_DIR, "blend_sweep.csv"), blend_rows)
    distinct = {(r["frr"], r["far"]) for r in blend_rows}
    report("")
    report(f"Swept the confidence-blend weights (currently 0.6 distance / "
           f"0.4 vote, `face_recognizer.py:151`) → `blend_sweep.csv`. "
           f"{len(distinct)} distinct (FRR, FAR) outcome(s) across "
           f"{len(blend_rows)} weightings.")
    if len(distinct) == 1:
        report("")
        report("> **Finding: the blend weights do not affect the decision "
               "here.** Every weighting produces identical error rates, "
               "because the `MIN_FACE_CONFIDENCE` floor is never the binding "
               "constraint — the tolerance gate decides every case first. The "
               "0.6/0.4 split is therefore undocumented *and* currently "
               "inconsequential to accept/reject, though it still sets the "
               "number shown to users and tested by the high-risk floor.")

    # ── Figures ──
    if make_plots:
        report.heading("6. Figures")
        written = [
            plots.score_distributions(
                a["genuine"], a["impostor"], tolerance,
                title=f"Cosine distance distributions (det_size {gallery_det})"),
            plots.roc_curve(a["genuine"], a["impostor"], tolerance,
                            title="ROC — pairwise verification"),
            plots.far_frr_sweep(a["genuine"], a["impostor"], tolerance,
                                metrics.eer(a["genuine"], a["impostor"])),
            plots.tolerance_sweep(tol_rows, tolerance),
            plots.confidence_histogram(
                b_deployed["genuine_accept_confidences"], HIGH_RISK_FLOOR),
            plots.det_size_comparison({
                f"probe {gallery_det}": b_matched,
                f"probe {probe_det} (deployed)": b_deployed,
            }),
        ]
        for path in written:
            report(f"- `{os.path.basename(path)}`")

    report.heading("7. What this does not measure")
    if b_deployed["accuracy"] == 1.0:
        report("> **Do not quote this as 100% accuracy.** A flawless Protocol "
               "B score on this data is a statement about the *dataset's "
               "difficulty*, not the system's ceiling. With d′ ≈ "
               f"{s['d_prime']:.1f} the two populations barely overlap, so any "
               "reasonable threshold separates them. The honest claim is "
               "narrow and defensible: *on 21 users captured in a single "
               "session, the deployed rule made no errors, bounding its error "
               f"rate below {metrics.rule_of_three(n):.2%}.* Harder data is "
               "what would move that bound, and §1 says why this data is easy.")
        report("")
    report("- **Single capture session** — the dominant limitation (§1). "
           "Same lighting, day, and appearance within each user.")
    report("- **No presentation attacks.** Impostor trials are other enrolled "
           "people, not photographs, screens, or masks. This measures "
           "recognition, not anti-spoofing.")
    report("- **Still images only.** No webcam capture, motion blur, "
           "compression, or real-world lighting.")
    report("- **21 users.** Impostor difficulty grows with gallery size; a "
           "production gallery is orders of magnitude larger.")
    report("- **Face only.** Fingerprint and the fused decision are steps 2b "
           "and 4 of `docs/fusion_architecture.md`.")

    return report


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--gallery-det", type=int, default=640)
    parser.add_argument("--probe-det", type=int, default=320)
    parser.add_argument("--no-plots", action="store_true")
    args = parser.parse_args()

    try:
        report = run(args.gallery_det, args.probe_det,
                     make_plots=not args.no_plots)
    except FileNotFoundError as e:
        print(f"\n{e}\n")
        return 1

    path = os.path.join(OUTPUT_DIR, "face_eval_report.md")
    report.write(path)
    print(f"\nReport written to {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
